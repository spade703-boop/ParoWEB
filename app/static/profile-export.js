(() => {
  "use strict";

  let rendererPromise;

  function loadRenderer() {
    if (!rendererPromise) {
      rendererPromise = new Promise((resolve, reject) => {
        const script = document.createElement("script");
        script.src = "/static/vendor/html2canvas-1.4.1.min.js";
        script.onload = () => resolve(window.html2canvas);
        script.onerror = () => reject(new Error("个人总览图片模块加载失败，请重试。"));
        script.addEventListener("load", () => script.remove());
        script.addEventListener("error", () => script.remove());
        document.head.append(script);
      }).catch((error) => {
        rendererPromise = null;
        throw error;
      });
    }
    return rendererPromise;
  }

  function node(tag, className, text) {
    const element = document.createElement(tag);
    if (className) element.className = className;
    if (text != null) element.textContent = text;
    return element;
  }

  function avatar(url, name, side, small = false) {
    const element = node("span", `ava ${side}${small ? " sm" : ""}`, String(name || "?").slice(0, 1));
    if (url) {
      const image = node("img");
      image.alt = "";
      image.src = url;
      image.addEventListener("error", () => image.remove());
      element.append(image);
    }
    return element;
  }

  function count(value, className = "ccount", prefix = "") {
    const element = node("span", className, `${prefix}${Number(value) || 0}`);
    element.append(node("span", "unit", "次"));
    return element;
  }

  function section(title) {
    const element = node("div", "sec");
    element.append(node("span", "mark"), node("span", null, title));
    return element;
  }

  function ranks(items, side, title) {
    const card = node("div", `cbox ${side}`);
    card.append(section(title));
    if (!items.length) card.append(node("div", "empty", "还没有抽取记录"));
    items.slice(0, 3).forEach((item, index) => {
      const row = node("div", "crow");
      const icons = node("span", "avas");
      icons.append(avatar(item.avatar_url, item.name, side));
      row.append(
        node("span", `tag${index === 0 ? " solid" : ""}`, `TOP${index + 1}`),
        node("span", `cnames ${side === "akito" ? "a" : "t"}`, item.name),
        icons,
        count(item.count),
      );
      card.append(row);
    });
    return card;
  }

  function dishes(items) {
    if (!items.length) return node("div", "empty", "还没有抽到做饭彩蛋");
    const wrap = node("div", "dish-wrap");
    items.forEach((item) => {
      const dish = node("span", "dish");
      const icons = node("span", "avas");
      icons.append(avatar(item.akito_avatar_url, item.akito_name, "akito", true), avatar(item.toya_avatar_url, item.toya_name, "toya", true));
      const names = node("span", "dn");
      names.append(node("span", "a", item.akito_name), document.createTextNode("×"), node("span", "t", item.toya_name));
      dish.append(icons, names);
      if (item.count > 1) dish.append(node("span", "dc", `×${item.count}`));
      wrap.append(dish);
    });
    return wrap;
  }

  function special(item) {
    const strip = node("div", "fr-strip");
    const icons = node("span", "avas");
    const urls = item.asset_urls?.length ? item.asset_urls : [null];
    urls.slice(0, 3).forEach((url, index) => icons.append(avatar(url, item.label, index % 2 ? "toya" : "akito")));
    strip.append(icons, node("span", "egg-name", item.label), count(item.count, "ccount", "累计触发 "));
    return strip;
  }

  function buildReport(profile) {
    const report = node("div", "profile-export");
    report.setAttribute("aria-hidden", "true");
    report.inert = true;
    const topbar = node("div", "topbar");
    topbar.append(node("span"), node("span"));
    const head = node("div", "head");
    const title = node("div", "title");
    title.append(document.createTextNode("我的"), node("span", "a", "彰"), node("span", "t", "冬"), document.createTextNode("派生记录"));
    head.append(title);
    const stats = node("div", "stats");
    [["累计抽取派生次数", profile.draw_count], ["累计抽到做饭的次数", profile.cooking_count]].forEach(([label, value]) => {
      const stat = node("div", "stat");
      stat.append(node("div", "stat-label", label), count(value, "stat-num"));
      stats.append(stat);
    });
    report.append(topbar, head, stats,
      ranks(profile.akito_top || [], "akito", "抽到最多的彰人派生 TOP 3"),
      ranks(profile.toya_top || [], "toya", "抽到最多的冬弥派生 TOP 3"),
      section("抽到的派生饭"), dishes(profile.cooking_pairs || []),
    );
    (profile.special_counts || []).forEach((item) => report.append(special(item)));
    report.append(node("div", "foot", "Generated by 寒星"));
    return report;
  }

  async function renderCanvas(profile) {
    if (!profile) throw new Error("个人数据尚未加载，请稍后重试。");
    const render = await loadRenderer();
    const report = buildReport(profile);
    document.body.append(report);
    try {
      const fonts = await Promise.all([400, 700, 900].map((weight) => document.fonts.load(`${weight} 16px "Paro Report Sans"`, "我的彰冬派生记录")));
      if (fonts.some((faces) => !faces.length)) throw new Error("个人总览字体尚未加载，请刷新页面后重试。");
      await Promise.all(Array.from(report.querySelectorAll("img"), (image) => image.decode().catch(() => image.remove())));
      if (report.offsetHeight * 2 > 16000) throw new Error("做饭组合过多，总览图片过长，请使用选择导出。");
      return await render(report, {
        scale: 2,
        backgroundColor: null,
        logging: false,
        windowWidth: Math.max(680, window.innerWidth),
        onclone(clonedDocument) {
          clonedDocument.querySelector(".profile-export").style.left = "0";
        },
      });
    } catch (error) {
      if (error.name === "NetworkError") throw new Error("个人总览字体加载失败，请刷新页面后重试。");
      throw error;
    } finally {
      report.remove();
    }
  }

  window.ParoProfileExporter = Object.freeze({ renderCanvas });
})();
